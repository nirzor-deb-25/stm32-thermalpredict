#ifndef STM32_REGS_H
#define STM32_REGS_H

#include <stdint.h>

#define REG32(address) \
    (*(volatile uint32_t *)(uintptr_t)(address))

/* Clock control */
#define RCC_AHB1ENR    REG32(0x40023830UL)
#define RCC_APB1ENR    REG32(0x40023840UL)
#define RCC_APB1RSTR   REG32(0x40023820UL)

/* GPIOB: LEDs and planned I2C1 pins PB8/PB9 */
#define GPIOB_MODER    REG32(0x40020400UL)
#define GPIOB_OTYPER   REG32(0x40020404UL)
#define GPIOB_OSPEEDR  REG32(0x40020408UL)
#define GPIOB_PUPDR    REG32(0x4002040CUL)
#define GPIOB_IDR      REG32(0x40020410UL)
#define GPIOB_ODR      REG32(0x40020414UL)
#define GPIOB_BSRR     REG32(0x40020418UL)
#define GPIOB_AFRH     REG32(0x40020424UL)

/* GPIOD: USART3 on PD8/PD9 */
#define GPIOD_MODER    REG32(0x40020C00UL)
#define GPIOD_OTYPER   REG32(0x40020C04UL)
#define GPIOD_OSPEEDR  REG32(0x40020C08UL)
#define GPIOD_PUPDR    REG32(0x40020C0CUL)
#define GPIOD_AFRH     REG32(0x40020C24UL)

/* I2C1 */
#define I2C1_CR1       REG32(0x40005400UL)
#define I2C1_CR2       REG32(0x40005404UL)
#define I2C1_OAR1      REG32(0x40005408UL)
#define I2C1_OAR2      REG32(0x4000540CUL)
#define I2C1_DR        REG32(0x40005410UL)
#define I2C1_SR1       REG32(0x40005414UL)
#define I2C1_SR2       REG32(0x40005418UL)
#define I2C1_CCR       REG32(0x4000541CUL)
#define I2C1_TRISE     REG32(0x40005420UL)

/* USART3 */
#define USART3_SR      REG32(0x40004800UL)
#define USART3_DR      REG32(0x40004804UL)
#define USART3_BRR     REG32(0x40004808UL)
#define USART3_CR1     REG32(0x4000480CUL)
#define USART3_CR2     REG32(0x40004810UL)
#define USART3_CR3     REG32(0x40004814UL)

/* Cortex-M4 */
#define SCB_VTOR       REG32(0xE000ED08UL)
#define CORE_DEMCR     REG32(0xE000EDFCUL)
#define DWT_CTRL       REG32(0xE0001000UL)
#define DWT_CYCCNT     REG32(0xE0001004UL)

#endif